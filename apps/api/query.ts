import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DuckDBInstance } from "@duckdb/node-api";
import type { Database } from "./db.js";
import type { Storage } from "./storage.js";
let active = 0;
export async function queryEvidence(
  db: Database,
  storage: Storage,
  tenant: string,
  runId: string,
  filters: { kind?: string; processId?: string; after: number; limit: number },
) {
  await db.get(tenant, runId);
  if (active >= 4)
    throw Object.assign(new Error("Query service is busy; retry shortly"), {
      statusCode: 429,
    });
  active++;
  const directory = await mkdtemp(join(tmpdir(), "verklikker-query-"));
  let instance: DuckDBInstance | undefined;
  try {
    const artifacts = (
      await db.pool.query(
        "SELECT * FROM artifacts WHERE tenant_id=$1 AND run_id=$2 AND kind='index' AND committed ORDER BY created_at",
        [tenant, runId],
      )
    ).rows;
    if (artifacts.reduce((n, a) => n + Number(a.size), 0) > 512 * 1024 * 1024)
      throw Object.assign(
        new Error(
          "This run exceeds the online query budget; download the evidence bundle",
        ),
        { statusCode: 422 },
      );
    if (!artifacts.length) return [];
    const paths: string[] = [];
    for (const a of artifacts) {
      const path = join(directory, a.id + ".parquet");
      await storage.download(a.object_key, path);
      paths.push(path);
    }
    instance = await DuckDBInstance.create(":memory:", {
      memory_limit: "256MB",
      threads: "1",
      enable_external_access: "true",
    });
    const c = await instance.connect();
    try {
      const files = paths
        .map((p) => "'" + p.replaceAll("'", "''") + "'")
        .join(",");
      // Paths are generated by the service; user input is only bound as values.
      const sql = `SELECT * FROM read_parquet([${files}],union_by_name=true) WHERE sequence > $1 ${filters.kind ? "AND kind=$2" : ""} ORDER BY sequence LIMIT ${filters.limit}`;
      const deadline = setTimeout(() => c.interrupt(), 10000);
      try {
        const result = await c.runAndReadAll(
          sql,
          filters.kind ? [filters.after, filters.kind] : [filters.after],
        );
        return result.getRowObjectsJson().map((row) => ({
          ...row,
          sequence: Number(row.sequence),
          data: typeof row.data === "string" ? JSON.parse(row.data) : row.data,
        }));
      } finally {
        clearTimeout(deadline);
      }
    } finally {
      c.closeSync();
    }
  } finally {
    instance?.closeSync();
    await rm(directory, { recursive: true, force: true });
    active--;
  }
}
